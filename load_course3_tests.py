def load_tests(tests_list, module_label):
    global total_loaded
    for test in tests_list:
        try:
            cursor.execute('''
                INSERT INTO tests (module_no, lesson_no, question_number, question_text, options, correct_answers, explanations, is_multiple_choice)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            ''', (
                test['module_no'], test['lesson_no'], test['question_number'], test['question_text'],
                json.dumps(test['options'], ensure_ascii=False),
                json.dumps(test['correct_answers']),
                json.dumps(test['explanations'], ensure_ascii=False),
                test['is_multiple_choice']
            ))
            total_loaded += 1
        except Exception as e:
            print(f"⚠️  Пропущен тест Модуль {test['module_no']}, Урок {test['lesson_no']}, Тест {test['question_number']}: {e}")
    print(f"✅ {module_label}: загружено {len(tests_list)} тестов")


load_tests(module_10_tests, "Модуль 10 (Курс 3, Модуль 1) — Основы веб-разработки с ИИ")
